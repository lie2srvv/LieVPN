def to_kazakh(text):
    if not isinstance(text, str):
        return text
    if text in KK_TRANSLATIONS:
        return KK_TRANSLATIONS[text]
    res = text
    for src, dst in KK_WORD_REPLACEMENTS:
        res = res.replace(src, dst)
    return res

updated_count = 0
for k, v in list(kk.items()):
    if k.startswith('@'):
        continue
    if k in KK_TRANSLATIONS:
        if kk[k] != KK_TRANSLATIONS[k]:
            kk[k] = KK_TRANSLATIONS[k]
            updated_count += 1
    else:
        new_val = to_kazakh(v)
        if new_val != v:
            kk[k] = new_val
            updated_count += 1

with open('arb/intl_kk.arb', 'w', encoding='utf-8') as f:
    json.dump(kk, f, ensure_ascii=False, indent=2)

print(f"Kazakh updated {updated_count} strings!")
