def to_belarusian(text):
    if not isinstance(text, str):
        return text
    if text in BE_TRANSLATIONS:
        return BE_TRANSLATIONS[text]
    res = text
    for src, dst in BE_WORD_REPLACEMENTS:
        res = res.replace(src, dst)
    return res

updated_count = 0
for k, v in list(be.items()):
    if k.startswith('@'):
        continue
    if k in BE_TRANSLATIONS:
        if be[k] != BE_TRANSLATIONS[k]:
            be[k] = BE_TRANSLATIONS[k]
            updated_count += 1
    else:
        new_val = to_belarusian(v)
        if new_val != v:
            be[k] = new_val
            updated_count += 1

with open('arb/intl_be.arb', 'w', encoding='utf-8') as f:
    json.dump(be, f, ensure_ascii=False, indent=2)

print(f"Belarusian updated {updated_count} strings!")
