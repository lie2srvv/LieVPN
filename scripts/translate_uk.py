def to_ukrainian(text):
    if not isinstance(text, str):
        return text
    # Check exact dictionary first
    if text in UK_TRANSLATIONS:
        return UK_TRANSLATIONS[text]
    
    # Process word replacements
    res = text
    for src, dst in WORD_REPLACEMENTS:
        res = res.replace(src, dst)
    
    # Character adjustments if still has Russian-specific characters
    # e.g. 'ы' -> 'и', 'э' -> 'е', 'ъ' -> "'", 'ё' -> 'е'
    # but only for isolated remnants
    res = res.replace(" настройки", " налаштування")
    res = res.replace("Настройки", "Налаштування")
    res = res.replace("Сервер перестал отвечать", "Сервер перестав відповідати")
    res = res.replace("Переподключение", "Перепідключення")
    res = res.replace("переподключение", "перепідключення")
    res = res.replace("Царь Доната", "Цар Донату")
    res = res.replace("Личный кабинет", "Особистий кабінет")
    res = res.replace("личный кабинет", "особистий кабінет")
    res = res.replace("О программе", "Про програму")
    res = res.replace("Поддержка", "Підтримка")
    res = res.replace("поддержка", "підтримка")
    res = res.replace("Проверить обновления", "Перевірити оновлення")
    res = res.replace("проверить обновления", "перевірити оновлення")
    return res

updated_count = 0
for k, v in list(uk.items()):
    if k.startswith('@'):
        continue
    if k in UK_TRANSLATIONS:
        if uk[k] != UK_TRANSLATIONS[k]:
            uk[k] = UK_TRANSLATIONS[k]
            updated_count += 1
    else:
        new_val = to_ukrainian(v)
        if new_val != v:
            uk[k] = new_val
            updated_count += 1

