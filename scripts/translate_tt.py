def to_tiktok(text):
    if not isinstance(text, str):
        return text
    if text in TT_TRANSLATIONS:
        return TT_TRANSLATIONS[text]
    res = text
    for src, dst in TT_WORD_REPLACEMENTS:
        res = res.replace(src, dst)
    return res

updated_count = 0
for k, v in list(tt.items()):
    if k.startswith('@'):
        continue
    if k in TT_TRANSLATIONS:
        if tt[k] != TT_TRANSLATIONS[k]:
            tt[k] = TT_TRANSLATIONS[k]
            updated_count += 1
    else:
        new_val = to_tiktok(v)
        if new_val != v:
            tt[k] = new_val
            updated_count += 1

with open('arb/intl_tt.arb', 'w', encoding='utf-8') as f:
    json.dump(tt, f, ensure_ascii=False, indent=2)

print(f"TikTok updated {updated_count} strings!")
